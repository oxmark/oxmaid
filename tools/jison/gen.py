"""Writes the LALR tables of a Jison parser dump (dump.js) as Rust constants
read by src/jison.rs.

usage: python3 gen.py dump.json out.rs
"""
import json, sys

d = json.load(open(sys.argv[1]))
KIND = {1: 1, 2: 2, 3: 3}

def enc(v):
    # goto: kind 0; shift 1; reduce 2; accept 3. Value in the low 16 bits.
    if isinstance(v, int):
        return v
    return (KIND[v[0]] << 16) | (v[1] if len(v) > 1 else 0)

offsets, actions = [0], []
for state in d['table']:
    for sym in sorted(state, key=int):
        actions.append(f'({sym}, {enc(state[sym])})')
    offsets.append(len(actions))

def rows(vals, per):
    return '\n'.join('    ' + ' '.join(v + ',' for v in vals[i:i + per]) for i in range(0, len(vals), per))

prods = [(0, 0)] + [tuple(p) for p in d['productions'][1:]]
defaults = sorted((int(k), enc(v)) for k, v in d['defaultActions'].items())
syms = sorted((v, k) for k, v in d['symbols'].items())
out = [
    '// Generated by tools/jison/gen.py from Mermaid 12.3\'s compiled parser. Do not edit.',
    '',
    'use crate::jison::Tables;',
    '',
    'pub(super) const TABLES: Tables = Tables {',
    f'    offsets: &[\n{rows([str(o) for o in offsets], 16)}\n    ],',
    f'    actions: &[\n{rows(actions, 8)}\n    ],',
    f'    defaults: &[\n{rows([f"({s}, {a})" for s, a in defaults], 8)}\n    ],',
    f'    productions: &[\n{rows([f"({a}, {b})" for a, b in prods], 10)}\n    ],',
    '};',
    '',
    '/// Grammar symbols.',
    '#[allow(dead_code)]',
    'pub(super) mod sym {',
]
for v, k in syms:
    name = ''.join(c if c.isalnum() else '_' for c in k).upper().strip('_') or f'S{v}'
    if str(v) not in d['terminals']:
        # Nonterminals, which may share a name with a terminal (`style`).
        name = 'N_' + name
    if name[0].isdigit():
        name = 'S' + name
    out.append(f'    pub const {name}: u16 = {v};')
out.append('}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
