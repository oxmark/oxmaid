"""Writes src/font_metrics_svg.rs: Times New Roman (Liberation Serif) advances
and kerning measured in Chromium (measure.js), plus vertical glyph extents of
Liberation Serif and Liberation Sans read with fontTools.

usage: python3 gen.py serif.json out.rs
"""
import json, sys
from fontTools.ttLib import TTFont

serif = json.load(open(sys.argv[1]))
FONTS = {
    'TIMES': '/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf',
    'ARIAL': '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf',
}

def rows(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append('    ' + ' '.join(v + ',' for v in vals[i:i + per]))
    return '\n'.join(out)

out = ['//! Metrics for SVG `<text>` measured by `getBBox()` in Chromium, generated by',
       '//! `tools/metrics`. Advances are in units of a 2048 em, for U+0020..U+024F.',
       '//! Times New Roman (Liberation Serif) is what Mermaid\'s sequence diagrams',
       '//! measure labels with in a default page; Arial (Liberation Sans) is what',
       '//! drawn labels use. Vertical extents are each glyph\'s (yMin, yMax).',
       '']
adv = serif['adv']
out.append(f'pub(crate) const TIMES_ADVANCE: [u16; {len(adv)}] = [')
out.append(rows([str(a) for a in adv], 16))
out.append('];')
out.append('')
kern = serif['kern']
out.append(f'pub(crate) const TIMES_KERN: [(u8, u8, i16); {len(kern)}] = [')
out.append(rows([f'({a}, {b}, {d})' for a, b, d in kern], 6))
out.append('];')
for name, path in FONTS.items():
    f = TTFont(path)
    hh = f['hhea']; cmap = f.getBestCmap(); glyf = f['glyf']
    ext = []
    for c in range(32, 0x250):
        g = cmap.get(c)
        if g and glyf[g].numberOfContours != 0 and hasattr(glyf[g], 'yMax'):
            ext.append((glyf[g].yMin, glyf[g].yMax))
        else:
            ext.append((0, 0))
    out.append('')
    out.append(f'pub(crate) const {name}_ASCENT: f64 = {hh.ascent}.0;')
    out.append(f'pub(crate) const {name}_DESCENT: f64 = {-hh.descent}.0;')
    out.append(f'pub(crate) const {name}_EXTENT: [(i16, i16); {len(ext)}] = [')
    out.append(rows([f'({a}, {b})' for a, b in ext], 8))
    out.append('];')
    if name == 'TIMES':
        hext = []
        for c in range(32, 0x250):
            g = cmap.get(c)
            if g and glyf[g].numberOfContours != 0 and hasattr(glyf[g], 'xMax'):
                hext.append((glyf[g].xMin, glyf[g].xMax))
            else:
                hext.append((0, 0))
        out.append('')
        out.append('/// Each glyph\'s (xMin, xMax): `getBBox()` widens a line to its ink.')
        out.append(f'pub(crate) const {name}_HEXTENT: [(i16, i16); {len(hext)}] = [')
        out.append(rows([f'({a}, {b})' for a, b in hext], 8))
        out.append('];')
        rows_x = []
        for c, a in serif['extra']:
            g = cmap.get(c)
            gl = glyf[g] if g else None
            if gl is not None and gl.numberOfContours != 0 and hasattr(gl, 'xMax'):
                rows_x.append(f'({c:#x}, {a}, {gl.xMin}, {gl.xMax}, {gl.yMin}, {gl.yMax})')
            else:
                rows_x.append(f'({c:#x}, {a}, 0, 0, 0, 0)')
        out.append('')
        out.append('/// Code points past U+024F: (char, advance, xMin, xMax, yMin, yMax).')
        out.append(f'pub(crate) const {name}_EXTRA: [(u32, u16, i16, i16, i16, i16); {len(rows_x)}] = [')
        out.append(rows(rows_x, 2))
        out.append('];')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
